import assert from 'node:assert/strict';
import {isPublished,canonicalPath,publicDocument,safeJson} from '../src/lib/publishing.ts';
import {localizeLink,isMigrationEntryPublished} from '../src/lib/legacy-links.mjs';
const now=new Date('2026-09-27T04:00:00Z');
assert.equal(isPublished({data:{draft:true,status:'published'}},now),false);
assert.equal(isPublished({data:{draft:false,status:'approved'}},now),false);
assert.equal(isPublished({data:{status:'draft'}},now),false);
assert.equal(isPublished({data:{status:'published',publishAt:'2026-09-28T00:00:00Z'}},now),false);
assert.equal(isPublished({data:{status:'published',publishAt:'2026-09-27T04:00:00Z'}},now),true);
assert.equal(isPublished({data:{status:'published',date:'2026-09-28'}},now),false);
assert.equal(isPublished({data:{status:'published',publishAt:'invalid'}},now),false);
assert.equal(isPublished({data:{}},now),true); // Existing Chinese entries remain published.
assert.equal(canonicalPath('/products'),'/products/');
assert.equal(canonicalPath('/cn/products///'),'/cn/products/');
assert.equal(canonicalPath('/'),'/');
assert.equal(canonicalPath('/cn/'),'/cn/');
assert.equal(isPublished({data:{draft:true,status:'published',publishAt:'2026-01-01'}},now),false);
assert.equal(isPublished({data:{draft:false,status:'approved',publishAt:'2026-01-01'}},now),false);
assert.equal(isPublished({data:{status:'published',publishAt:'2026-09-27T12:00:01+08:00'}},now),false);
assert.equal(isPublished({data:{status:'published',publishAt:'2026-09-27T12:00:00+08:00'}},now),true);
assert.equal(isPublished({data:{status:'published',date:'invalid'}},now),false);
assert.equal(publicDocument({visibility:'internal',status:'current',number:'test',date:'2026-01-01',scope:'test',url:'https://example.com'}),false);
assert.equal(publicDocument({visibility:'public',status:'archived',number:'test',date:'2026-01-01',scope:'test',url:'https://example.com'}),false);
assert.equal(publicDocument({visibility:'public',status:'current',number:'test',date:'2020-01-01',expiry:'2020-12-31',scope:'test',url:'https://example.com'}),false);
assert(!safeJson({text:'</script><script>alert(1)</script>'}).includes('<'));
assert.deepEqual(JSON.parse(safeJson({name:'裕明兴',text:'</script>',zero:0})),{name:'裕明兴',text:'</script>',zero:0});
assert.equal(localizeLink('/en/products/c304-00-304-flatware/?product=C304-00#specs','en'),'/products/c304-00-304-flatware/?product=C304-00#specs');
assert.equal(localizeLink('/en/products/c304-00-304-flatware/','zh-CN'),'/cn/products/c304-00-304-flatware/');
assert.equal(localizeLink('/en/factory/','en'),'/about/');
assert.equal(localizeLink('/factory/','zh-CN'),'/cn/about/');
assert.equal(localizeLink('/products?cat=flatware-sets','zh-CN'),'/cn/stainless-steel-cutlery/');
assert.equal(localizeLink('/uploads/catalogue-20261016/c304-00.webp','zh-CN'),'/uploads/catalogue-20261016/c304-00.webp');
assert.equal(localizeLink('/admin/','zh-CN'),'/admin/');
assert.equal(localizeLink('https://example.com/en/products/','zh-CN'),'https://example.com/en/products/');
assert.equal(isMigrationEntryPublished({},'en',now),false);
assert.equal(isMigrationEntryPublished({status:'published'},'en',now),false);
assert.equal(isMigrationEntryPublished({draft:false},'en',now),false);
assert.equal(isMigrationEntryPublished({draft:false,status:'published'},'en',now),true);
assert.equal(isMigrationEntryPublished({},'zh-CN',now),true);
assert.equal(isMigrationEntryPublished({draft:false,status:'published',publishAt:'2026-01-01',date:'2030-01-01'},'en',now),true);
assert.equal(isMigrationEntryPublished({draft:false,status:'published',publishAt:'invalid'},'en',now),false);
console.log('PASS: draft/scheduling, document visibility, JSON escaping, bilingual final URLs and preserved query/fragment/assets.');
